function buildFreeExtras(saju, input) {
  // 타고난 재능 TOP2 (십신 구성)
  const ranked = Object.entries(saju.godCounts).sort((a, b) => b[1] - a[1]);
  const talents = ranked.slice(0, 2).map(([g]) => ({ god: g, ...TALENT_TEXT[g] }));

  // 2026 운세 지수 (결정적: 같은 사주는 항상 같은 점수)
  const rel2026 = tenGodRelation(saju.dayEl, "fire");
  const dp = saju.pillars.day;
  const catScore = (i, godKey) => {
    const base = 62 + ((dp.stem * 7 + dp.branch * 3 + i * 13) % 29);
    const bonus = (saju.godCounts[godKey] >= 2 ? 4 : 0) + (rel2026 === godKey ? 5 : 0);
    return Math.min(97, base + bonus);
  };
  const scores = [
    { label: "재물", score: catScore(0, "재성") },
    { label: "애정", score: catScore(1, "비겁") },
    { label: "직업", score: catScore(2, "관성") },
    { label: "건강", score: catScore(3, "인성") },
  ];
  const total = Math.round(scores.reduce((s, c) => s + c.score, 0) / 4);

  // 오늘의 한 줄 (매일 갱신)
  const dayN = Math.floor(Date.now() / 86400000);
  const todayLine = DAILY_LINES[(dayN + dp.stem + dp.branch) % DAILY_LINES.length];

  // 연화의 예고 멘트 (가장 궁금한 포인트로 끊기)
  const nowY = new Date().getFullYear();
  const age = Math.max(0, nowY - input.y);
  const cur = saju.daeun.list.find(d => age >= d.fromAge && age <= d.toAge) || saju.daeun.list[0];
  const curIdx = saju.daeun.list.indexOf(cur);
  const next = saju.daeun.list[curIdx + 1];

  let cliffhanger;
  if (saju.sinsal.length > 0) {
    const names = saju.sinsal.map(s => s.name).join("과 ");
    cliffhanger = `허… 그런데 자네 팔자에 눈에 밟히는 게 있네. <b>${names}</b>이 박혀 있어. 이게 자네한테 복이 될지 화가 될지는 쓰기 나름인데… 그 얘기는 복채를 놓고 마저 함세.`;
  } else if (next && cur.toAge - age <= 3) {
    cliffhanger = `자네, 지금 큰 물길이 바뀌기 직전이야. <b>${next.fromAge}살부터 ${next.tenGod} 대운</b>이 들어오는데, 이건 준비한 사람과 아닌 사람의 10년이 갈리는 운이네. 마저 들어보시게.`;
  } else {
    cliffhanger = `올해 <b>병오년 불기운</b>이 자네 사주와 부딪히는 모양이 예사롭지 않아. 좋게 쓰면 크게 얻고, 모르고 지나면 두고두고 아까운 해야. 마저 들어보시게.`;
  }

  return { talents, scores, total, todayLine, cliffhanger, sinsal: saju.sinsal };
}

/* 잠금 섹션 첫 문장 미리보기 (클리프행어) */
function previewSentence(html) {
  const tmp = document.createElement("div");
  tmp.innerHTML = html;
  const text = (tmp.textContent || "").trim().replace(/\s+/g, " ");
  const cut = text.search(/(다\.|요\.|네\.|야\.)/);
  if (cut > 0 && cut < 110) return text.slice(0, cut + 2);
  return text.slice(0, 80) + "…";
}

