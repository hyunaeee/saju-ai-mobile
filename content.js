/* ---------- 모임 궁합 (최대 10명 관계 분석) ---------- */
function analyzeGroup(people) {
  // people: [{name, y, m, d}] — 일주(일간·일지) 기반 페어와이즈 분석
  const ps = people.map(p => {
    const dp = dayPillar(p.y, p.m, p.d);
    return { ...p, stem: dp.stem, branch: dp.branch, el: STEMS[dp.stem].el };
  });

  const pairs = [];
  for (let i = 0; i < ps.length; i++) {
    for (let j = i + 1; j < ps.length; j++) {
      const a = ps[i], b = ps[j];
      let score = 52;
      const tags = [];
      const notes = [];

      if (hapStem(a.stem) === b.stem) { score += 28; tags.push("천간합"); }
      if (YUKHAP[a.branch] === b.branch) { score += 24; tags.push("육합"); }
      else if (SAMHAP_GROUP[a.branch] === SAMHAP_GROUP[b.branch] && a.branch !== b.branch) { score += 18; tags.push("삼합"); }
      if (chungBranch(a.branch) === b.branch) { score -= 34; tags.push("충"); }

      if (GENERATES[a.el] === b.el) { score += 7; notes.push(`${a.name}가 ${b.name}의 기운을 살립니다`); }
      if (GENERATES[b.el] === a.el) { score += 7; notes.push(`${b.name}가 ${a.name}의 기운을 살립니다`); }
      if (CONTROLS[a.el] === b.el) { score -= 5; }
      if (CONTROLS[b.el] === a.el) { score -= 5; }

      if ((CHEONEUL[b.stem] || []).includes(a.branch)) { score += 12; tags.push("귀인"); notes.push(`${a.name}는 ${b.name}의 천을귀인입니다`); }
      if ((CHEONEUL[a.stem] || []).includes(b.branch)) { score += 12; if (!tags.includes("귀인")) tags.push("귀인"); notes.push(`${b.name}는 ${a.name}의 천을귀인입니다`); }

      score += ((a.stem * 3 + b.branch * 5 + a.branch + b.stem) % 7) - 3; // 결정적 미세 편차
      score = Math.max(8, Math.min(98, score));

      let desc;
      if (tags.includes("충")) desc = "겉으론 친해도 오래 붙어 있으면 부딪히는 앙숙 기류입니다. 짧고 굵게 만나는 게 오히려 관계를 지킵니다.";
      else if (tags.includes("천간합")) desc = "만나자마자 통하는 합(合)의 인연 — 서로에게 없는 것을 정확히 채워주는 짝입니다.";
      else if (tags.includes("육합")) desc = "붙여두면 조용히 편안해지는 짝꿍 궁합입니다. 자리 배치만 잘해도 모임이 부드러워집니다.";
      else if (tags.includes("삼합")) desc = "함께 일을 도모할수록 시너지가 나는 시절인연입니다. 여행·프로젝트 조합으로 최적.";
      else if (tags.includes("귀인")) desc = "한쪽이 다른 쪽을 결정적으로 끌어주는 귀인 관계가 숨어 있습니다.";
      else if (score >= 62) desc = "무난히 서로를 살려주는 순환 관계입니다. 오래 가는 편안한 사이.";
      else desc = "나쁘지 않지만 접점이 옅은 사이 — 공통 관심사가 다리를 놓아줍니다.";

      pairs.push({ a: a.name, b: b.name, score, tags, notes, desc });
    }
  }

  pairs.sort((x, y) => y.score - x.score);
  const best = pairs[0];
  const worst = pairs[pairs.length - 1];
  const chungPairs = pairs.filter(p => p.tags.includes("충"));
  const gwiinNotes = [...new Set(pairs.flatMap(p => p.notes.filter(n => n.includes("천을귀인"))))];

  // 중재자: 충 페어 양쪽 모두와 62점 이상인 제3자
  const scoreOf = (x, y) => pairs.find(p => (p.a === x && p.b === y) || (p.a === y && p.b === x))?.score ?? 0;
  const bridges = [];
  for (const cp of chungPairs) {
    const bridge = ps.map(p => p.name).find(n => n !== cp.a && n !== cp.b && scoreOf(n, cp.a) >= 62 && scoreOf(n, cp.b) >= 62);
    if (bridge) bridges.push({ pair: cp, bridge });
  }

  // 복덩이: 평균 점수 최고
  const avg = {};
  ps.forEach(p => { avg[p.name] = 0; });
  pairs.forEach(p => { avg[p.a] += p.score; avg[p.b] += p.score; });
  ps.forEach(p => { avg[p.name] /= (ps.length - 1); });
  const lucky = ps.map(p => p.name).sort((x, y) => avg[y] - avg[x])[0];

  return { people: ps, pairs, best, worst, chungPairs, gwiinNotes, bridges, lucky };
}

