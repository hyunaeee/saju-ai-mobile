/* 잠금 섹션 첫 문장 미리보기 (클리프행어) */
function previewSentence(html) {
  const tmp = document.createElement("div");
  tmp.innerHTML = html;
  const text = (tmp.textContent || "").trim().replace(/\s+/g, " ");
  const cut = text.search(/(다\.|요\.|네\.|야\.)/);
  if (cut > 0 && cut < 110) return text.slice(0, cut + 2);
  return text.slice(0, 80) + "…";
}

