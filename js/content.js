function elementSummaryText(saju) {
  const dom = ELEMENTS[saju.dominant];
  const weak = ELEMENTS[saju.weakest];
  const domCount = saju.counts[saju.dominant];
  const weakCount = saju.counts[saju.weakest];
  let s = `당신의 사주는 <strong>${dom.kor}(${dom.han}) 기운이 ${domCount}개로 가장 강하고</strong>, `;
  s += weakCount === 0
    ? `<strong>${weak.kor}(${weak.han}) 기운은 없는</strong> 구조입니다. `
    : `<strong>${weak.kor}(${weak.han}) 기운이 ${weakCount}개로 가장 약한</strong> 구조입니다. `;
  s += `부족한 ${weak.kor} 기운을 채우는 맞춤 개운법은 심층 풀이에서 알려드립니다.`;
  return s;
}

